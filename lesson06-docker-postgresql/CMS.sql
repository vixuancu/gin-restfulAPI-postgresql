-- =================================================================
-- I. EXTENSIONS
-- =================================================================
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- =================================================================
-- II. BẢNG `users`
-- =================================================================
-- CREATE TABLE
CREATE TABLE IF NOT EXISTS users (
    user_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_uuid UUID NOT NULL DEFAULT gen_random_uuid () UNIQUE,
    user_username VARCHAR(50) UNIQUE NOT NULL,
    user_email VARCHAR(255) UNIQUE NOT NULL,
    user_password_hash VARCHAR(255) NOT NULL,
    user_role INT NOT NULL DEFAULT 1 CHECK (user_role IN (1, 2, 3)),
    user_created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    user_updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    user_deleted_at TIMESTAMPTZ DEFAULT NULL
);

-- COMMENT ON COLUMNS
COMMENT ON COLUMN users.user_role IS 'Vai trò người dùng: 1-user, 2-editor, 3-admin';

COMMENT ON COLUMN users.user_deleted_at IS 'Dùng cho soft delete. NULL = chưa xóa.';

-- CREATE INDEXES
CREATE INDEX IF NOT EXISTS idx_users_email ON users (user_email);

CREATE INDEX IF NOT EXISTS idx_users_role ON users (user_role);

CREATE INDEX IF NOT EXISTS idx_users_deleted_at ON users (user_deleted_at);

-- CREATE TRIGGER FOR `updated_at`
CREATE OR REPLACE FUNCTION update_user_updated_at()
RETURNS TRIGGER AS $$
BEGIN
   NEW.user_updated_at = NOW();
   RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER set_user_updated_at
BEFORE UPDATE ON users
FOR EACH ROW
EXECUTE FUNCTION update_user_updated_at();

