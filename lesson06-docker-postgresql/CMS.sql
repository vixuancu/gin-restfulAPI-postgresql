-- =================================================================
-- IV. BẢNG `articles`
-- =================================================================
-- CREATE TABLE
CREATE TABLE IF NOT EXISTS articles (
    article_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    article_uuid UUID NOT NULL DEFAULT gen_random_uuid () UNIQUE,
    article_author_id INT NOT NULL,
    article_category_id INT NOT NULL,
    article_title VARCHAR(255) NOT NULL,
    article_slug VARCHAR(255) UNIQUE NOT NULL,
    article_content TEXT,
    article_status INT NOT NULL DEFAULT 1 CHECK (article_status IN (1, 2)),
    article_published_at TIMESTAMPTZ DEFAULT NULL,
    article_created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    article_updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    article_deleted_at TIMESTAMPTZ DEFAULT NULL
);

-- COMMENT ON COLUMNS
COMMENT ON COLUMN articles.article_status IS 'Trạng thái bài viết: 1-draft, 2-published';

COMMENT ON COLUMN articles.article_deleted_at IS 'Dùng cho soft delete.';

-- CREATE INDEXES
CREATE INDEX IF NOT EXISTS idx_articles_author_id ON articles (article_author_id);

CREATE INDEX IF NOT EXISTS idx_articles_category_id ON articles (article_category_id);

CREATE INDEX IF NOT EXISTS idx_articles_slug ON articles (article_slug);

CREATE INDEX IF NOT EXISTS idx_articles_status ON articles (article_status);

CREATE INDEX IF NOT EXISTS idx_articles_deleted_at ON articles (article_deleted_at);

