-- VI. BẢNG `notifications`
-- =================================================================
-- CREATE TABLE
CREATE TABLE IF NOT EXISTS notifications (
    notification_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_uuid UUID NOT NULL DEFAULT gen_random_uuid () UNIQUE,
    notification_user_id INT NOT NULL,
    notification_content TEXT NOT NULL,
    notification_is_read BOOLEAN NOT NULL DEFAULT false,
    notification_created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- CREATE INDEXES
CREATE INDEX IF NOT EXISTS idx_notifications_user_id ON notifications (notification_user_id);

CREATE INDEX IF NOT EXISTS idx_notifications_is_read ON notifications (notification_is_read);

-- =================================================================
-- VII. ĐỊNH NGHĨA QUAN HỆ (FOREIGN KEYS)
-- =================================================================
ALTER TABLE articles
ADD CONSTRAINT fk_articles_author FOREIGN KEY (article_author_id) REFERENCES users (user_id) ON DELETE CASCADE;

ALTER TABLE articles
ADD CONSTRAINT fk_articles_category FOREIGN KEY (article_category_id) REFERENCES categories (category_id) ON DELETE RESTRICT;

ALTER TABLE comments
ADD CONSTRAINT fk_comments_article FOREIGN KEY (comment_article_id) REFERENCES articles (article_id) ON DELETE CASCADE;

ALTER TABLE comments
ADD CONSTRAINT fk_comments_user FOREIGN KEY (comment_user_id) REFERENCES users (user_id) ON DELETE CASCADE;

ALTER TABLE notifications
ADD CONSTRAINT fk_notifications_user FOREIGN KEY (notification_user_id) REFERENCES users (user_id) ON DELETE CASCADE;